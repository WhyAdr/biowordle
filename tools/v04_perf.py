"""Measure 78 vs research-preview performance without writing production assets.

Run after the research compiler: python tools/v04_perf.py --preview tools/v04_compiled_preview.json
Optional --browser runs isolated Chromium via the companion Node script. On Windows
loopback/Chromium may require sandbox bypass. Preview is not a production release.
"""
from __future__ import annotations

import argparse
import contextlib
import gzip
import hashlib
import io
import json
import shutil
import subprocess
import sys
import tempfile
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
import build_puzzles
from chem_engine import evaluate_chemle_feedback_from_spec

def digest(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()

def asset_tree(payload, directory):
    for d in (directory / 'data', directory / 'tests', directory / 'dist'):
        d.mkdir(parents=True, exist_ok=True)
    for source in ('app.js', 'index.html', 'styles.css', 'data/feedback_spec.json', 'tests/verify_golden_and_dom.mjs'):
        shutil.copyfile(ROOT / source, directory / source)
    (directory / 'data/puzzles.json').write_text(json.dumps(payload, indent=2), encoding='utf-8', newline='\n')
    data_js = '// Auto-generated by build_puzzles.py using RDKit — do not edit manually.\nwindow.BIOWORDLE_DATA = ' + json.dumps(payload, separators=(',', ':')) + ';\n'
    (directory / 'data/puzzles_data.js').write_text(data_js, encoding='utf-8', newline='\n')
    html = (ROOT / 'index.html').read_text(encoding='utf-8').replace('\r\n', '\n')
    css = (ROOT / 'styles.css').read_text(encoding='utf-8').replace('\r\n', '\n')
    app = (ROOT / 'app.js').read_text(encoding='utf-8').replace('\r\n', '\n')
    standalone = html.replace('<link rel="stylesheet" href="styles.css" />', f'<style>\n{css}\n</style>')
    standalone = standalone.replace('<script src="data/puzzles_data.js"></script>\n  <script src="app.js"></script>', f'<script>\n{data_js}\n</script>\n<script>\n{app}\n</script>')
    (directory / 'dist/biowordle_standalone.html').write_text(standalone, encoding='utf-8', newline='\n')
    start = time.perf_counter()
    build_puzzles.write_golden_feedback_vectors(payload, str(directory))
    golden_seconds = time.perf_counter() - start
    start = time.perf_counter()
    proc = subprocess.run(['node', str(directory / 'tests/verify_golden_and_dom.mjs')], cwd=directory, capture_output=True, text=True, encoding='utf-8', errors='replace')
    verify_seconds = time.perf_counter() - start
    def sized(p):
        raw = p.read_bytes()
        return {'raw_bytes': len(raw), 'gzip_level9_bytes': len(gzip.compress(raw, compresslevel=9, mtime=0))}
    return {'chemle_count': len(payload['chemle']), 'chemle_vectors': sum(len(x) for x in json.loads((directory/'tests/golden_feedback.json').read_text(encoding='utf-8'))['chemle_signatures'].values()), 'puzzles_data_js': sized(directory/'data/puzzles_data.js'), 'standalone_html': sized(directory/'dist/biowordle_standalone.html'), 'golden': sized(directory/'tests/golden_feedback.json'), 'golden_generation_seconds': golden_seconds, 'node_verification_seconds': verify_seconds, 'node_verifier_exit_code': proc.returncode, 'node_verifier_output': (proc.stdout + proc.stderr)[-1500:]}

def ranked_regression(old, new):
    oa = {r['id']:r for r in old['chemle'] if 'ranked' in r['game_eligibility']}
    na = {r['id']:r for r in new['chemle'] if 'ranked' in r['game_eligibility']}
    op = {r['id']:r for r in old['chemle'] if 'ranked' in r['guess_eligibility']}
    np = {r['id']:r for r in new['chemle'] if 'ranked' in r['guess_eligibility']}
    mismatches=[]
    if set(oa) == set(na) and set(op) == set(np):
        for g in op:
            for t in oa:
                a=evaluate_chemle_feedback_from_spec(op[g],oa[t],old['chemle_similarity'][g][t],old['feedback_spec']['profiles']['ranked'])['signature']
                b=evaluate_chemle_feedback_from_spec(np[g],na[t],new['chemle_similarity'][g][t],new['feedback_spec']['profiles']['ranked'])['signature']
                if a != b: mismatches.append([g,t,a,b])
    clue_changes=[i for i in oa.keys() & na.keys() if oa[i]['clue_ladder']['ranked']!=na[i]['clue_ladder']['ranked']]
    return {'ranked_answer_roster_equal':set(oa)==set(na), 'ranked_probe_roster_equal':set(op)==set(np), 'ranked_signature_pairs_checked':len(op)*len(oa) if not (set(oa)!=set(na) or set(op)!=set(np)) else 0, 'ranked_signature_mismatches':mismatches, 'ranked_clue_changes':clue_changes, 'baseline_schedule_hash':old['metadata']['chemle_schedule_hash'], 'preview_schedule_hash':new['metadata']['chemle_schedule_hash'], 'baseline_rules_hash':old['metadata']['chemle_rules_hash'], 'preview_rules_hash':new['metadata']['chemle_rules_hash'], 'warning':'The all-catalog Chemle rules hash keys Ranked persistence: a change archives/restarts old Ranked sessions even if schedule, feedback and clues remain identical.'}

def main():
    ap=argparse.ArgumentParser()
    ap.add_argument('--preview',type=Path,required=True)
    ap.add_argument('--output',type=Path,default=ROOT/'tools/v04_perf_results.json')
    ap.add_argument('--browser',action='store_true')
    ap.add_argument('--runs',type=int,default=2)
    args=ap.parse_args()
    old=json.loads((ROOT/'data/puzzles.json').read_text(encoding='utf-8'))
    new=json.loads(args.preview.read_text(encoding='utf-8'))
    spec=json.loads((ROOT/'data/feedback_spec.json').read_text(encoding='utf-8'))
    with contextlib.redirect_stdout(io.StringIO()):
        start=time.perf_counter();rebuilt=build_puzzles.build_all(spec);compile_seconds=time.perf_counter()-start
    out={'conditions':'Single run on this host; compile includes normal existing gates. Performance is a research preview, not release validation.', 'inputs':{'baseline_commit':'03febdf790c39b6d14202833af671af469146ba2','baseline_sha256':digest(ROOT/'data/puzzles.json'),'preview_sha256':digest(args.preview)},'baseline_build_all_seconds':compile_seconds,'rebuilt_baseline_dataset_matches':rebuilt['metadata']['dataset_version_hash']==old['metadata']['dataset_version_hash'],'ranked_regression':ranked_regression(old,new)}
    with tempfile.TemporaryDirectory(prefix='v04-perf-', dir=ROOT, ignore_cleanup_errors=True) as tmp:
        folder=Path(tmp); base=folder/'baseline'; preview=folder/'preview'
        out['baseline78']=asset_tree(old,base);out['preview120']=asset_tree(new,preview)
        if args.browser:
            p=subprocess.run(['node',str(ROOT/'tools/v04_perf_browser.mjs'),str(base),str(preview),str(args.runs)],cwd=ROOT,capture_output=True,text=True,encoding='utf-8',errors='replace',timeout=600)
            out['browser_exit_code']=p.returncode
            if p.returncode==0:out['browser']=json.loads(p.stdout)
            else:out['browser_error']=(p.stdout+p.stderr)[-3000:]
    args.output.write_text(json.dumps(out,ensure_ascii=False,indent=2)+'\n',encoding='utf-8',newline='\n')
    print(json.dumps(out,ensure_ascii=False,indent=2))
    if out['baseline78']['node_verifier_exit_code'] or out['preview120']['node_verifier_exit_code'] or out.get('browser_exit_code',0):sys.exit(1)

if __name__=='__main__':main()
